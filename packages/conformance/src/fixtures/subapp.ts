/** A sub-app that conforms, and the tools to break it on purpose.
 *
 * ⭐ WHY THE BASELINE IS A WHOLE APP. Every violating fixture in these
 * tests is this app with ONE thing changed, which is what makes each test
 * a statement about one rule instead of a statement about a hand-written
 * snippet that happens to fail. It also means the conforming case is
 * tested constantly: if any rule starts firing on ordinary, correct code,
 * the baseline test goes red before anyone ships a gate that cries wolf.
 *
 * The files below are written the way the host's own hand-written sub-apps
 * are (`shell-reference`, `docusign`) — including the banners, which
 * matter: a real generated file's header explains that it must not cache a
 * boolean or interpolate into SQL, so it CONTAINS the strings the checks
 * look for. A gate that trips on its own explanation is a gate nobody can
 * use, so the baseline carries those sentences deliberately.
 *
 * ⛔ `editFile` THROWS WHEN THE EDIT DOES NOT APPLY. A violating fixture
 * that silently failed to violate anything would make its test pass for
 * the wrong reason, and that test would then guard nothing forever. */
