export function fileIn(app: CandidateSubApp, path: string): CandidateFile {
  const file = app.files.find((candidate) => candidate.path === path);
  if (file === undefined) throw new Error(`fixture has no file at ${path}`);
  return file;
}

/** Replace `find` with `replacement` in one file. Throws when `find` is
 * not there — a fixture that failed to break is a test that proves
 * nothing, and it must fail loudly rather than pass quietly. */
export function editFile(app: CandidateSubApp, path: string, find: string, replacement: string): CandidateSubApp {
  const target = fileIn(app, path);
  if (!target.contents.includes(find)) {
    throw new Error(`fixture edit did not apply: ${path} does not contain ${JSON.stringify(find)}`);
  }
  return {
    files: app.files.map((file) => (file.path === path ? { path, contents: file.contents.replace(find, replacement) } : file)),
  };
}

/** Add a file, or replace one wholesale. */
export function withFile(app: CandidateSubApp, path: string, contents: string): CandidateSubApp {
  const exists = app.files.some((file) => file.path === path);
  return {
    files: exists
      ? app.files.map((file) => (file.path === path ? { path, contents } : file))
      : [...app.files, { path, contents }],
  };
}

export function withoutFile(app: CandidateSubApp, path: string): CandidateSubApp {
  const before = app.files.length;
  const files = app.files.filter((file) => file.path !== path);
  if (files.length === before) throw new Error(`fixture has no file at ${path} to remove`);
  return { files };
}
