import { describe, expect, it, vi } from "vitest";
import { TourPlayback } from "../tour-playback";
import { buildWalkthrough } from "../walkthrough";
import { candidate } from "./fixtures";

describe("received-artifact playback", () => {
  it("defers an accepted hidden draft's first assembly until its builder becomes active", () => {
    vi.useFakeTimers();
    const narrate = vi.fn();
    const playback = new TourPlayback({ navigate: vi.fn(), narrate, stopNarration: vi.fn() });
    const context = { roundId: "handoff", latestRoundId: "handoff", plan: buildWalkthrough(candidate()), buildReveal: true, active: false };
    playback.sync(context);
    vi.advanceTimersByTime(10000);
    expect(playback.getState().playing).toBe(false);
    expect(narrate).not.toHaveBeenCalled();
    playback.sync({ ...context, active: true });
    expect(playback.getState()).toMatchObject({ mode: "assembly", playing: true, revealedGroups: 0 });
    vi.advanceTimersByTime(3100);
    expect(playback.getState().mode).toBe("ready");
    expect(narrate).toHaveBeenCalledTimes(1);
    playback.sync(context);
    playback.sync({ ...context, active: true });
    expect(playback.getState()).toMatchObject({ mode: "ready", playing: false });
    expect(narrate).toHaveBeenCalledTimes(1);
    playback.dispose(); vi.useRealTimers();
  });
  it("finishes assembly on motion-off and does not replay when motion is re-enabled", () => {
    vi.useFakeTimers();
    const playback = new TourPlayback({ navigate: vi.fn(), narrate: vi.fn(), stopNarration: vi.fn() });
    const context = { roundId: "motion", latestRoundId: "motion", plan: buildWalkthrough(candidate()), buildReveal: true, active: true, motion: true };
    playback.sync(context);
    expect(playback.getState().mode).toBe("assembly");
    playback.sync({ ...context, motion: false });
    expect(playback.getState()).toMatchObject({ mode: "ready", playing: false, revealedGroups: context.plan.groups.length });
    expect(vi.getTimerCount()).toBe(0);
    playback.play(); playback.replayCreation();
    expect(vi.getTimerCount()).toBe(0);
    playback.sync(context);
    expect(playback.getState().mode).toBe("ready");
    playback.next();
    expect(playback.getState().step).toBe(1);
    playback.dispose(); vi.useRealTimers();
  });
  it("assembles actual module groups in under four seconds without navigating source or repeating on view churn", () => {
    vi.useFakeTimers();
    const input = candidate({ files: Array.from({ length: 1000 }, (_, i) => ({ path: `server/subapps/wc-clock/routes/source-${i}.ts`, contents: "// received", kind: "routes-domain" })) });
    const plan = buildWalkthrough(input);
    const navigate = vi.fn();
    const narrate = vi.fn();
    const playback = new TourPlayback({ navigate, narrate, stopNarration: vi.fn() });
    playback.sync({ roundId: "round-1", latestRoundId: "round-1", plan, buildReveal: true, active: true });
    expect(playback.getState().mode).toBe("assembly");
    vi.advanceTimersByTime(3500);
    expect(playback.getState()).toMatchObject({ mode: "ready", revealedGroups: plan.groups.length, playing: false });
    expect(navigate).not.toHaveBeenCalled();
    expect(narrate).toHaveBeenCalledTimes(1);
    playback.sync({ roundId: "round-1", latestRoundId: "round-1", plan: buildWalkthrough(input), buildReveal: true, active: true });
    expect(playback.getState().mode).toBe("ready");
    expect(narrate).toHaveBeenCalledTimes(1);
    playback.dispose();
    expect(vi.getTimerCount()).toBe(0);
    vi.useRealTimers();
  });
  it("pauses visual playback for accepted narration without cancelling that utterance", () => {
    vi.useFakeTimers();
    const narrate = vi.fn(() => true);
    const stopNarration = vi.fn();
    const playback = new TourPlayback({ navigate: vi.fn(), narrate, stopNarration });
    playback.sync({ roundId: "spoken", latestRoundId: "spoken", plan: buildWalkthrough(candidate()), buildReveal: false, active: true });
    const cancellations = stopNarration.mock.calls.length;
    playback.play();
    expect(narrate).toHaveBeenCalledTimes(1);
    expect(playback.getState()).toMatchObject({ mode: "walkthrough", playing: false, step: 0 });
    expect(vi.getTimerCount()).toBe(0);
    expect(stopNarration).toHaveBeenCalledTimes(cancellations);
    playback.dispose(); vi.useRealTimers();
  });
  it("cancels accepted paused narration when its retained builder is hidden", () => {
    const stopNarration = vi.fn();
    const playback = new TourPlayback({ navigate: vi.fn(), narrate: () => true, stopNarration });
    const context = { roundId: "owned-voice", latestRoundId: "owned-voice", plan: buildWalkthrough(candidate()), buildReveal: false, active: true };
    playback.sync(context);
    playback.play();
    expect(playback.getState().playing).toBe(false);
    const cancellations = stopNarration.mock.calls.length;
    playback.sync({ ...context, active: false });
    expect(stopNarration).toHaveBeenCalledTimes(cancellations + 1);
    playback.dispose();
  });
  it("clamps changed descriptor steps without replaying or narrating a same-round saved edit", () => {
    const narrate = vi.fn(); const playback = new TourPlayback({ navigate: vi.fn(), narrate, stopNarration: vi.fn() });
    const input = candidate(); const context = { roundId: "current", latestRoundId: "current", plan: buildWalkthrough(input), buildReveal: true, active: true };
    playback.sync({ ...context, buildReveal: false });
    for (let i = 0; i < 6; i += 1) playback.next();
    const spoken = narrate.mock.calls.length;
    const plan = buildWalkthrough(candidate({ files: input.files.filter(file => file.kind !== "web-module") }));
    playback.sync({ ...context, plan });
    expect(playback.getState().step).toBe(plan.steps.length - 1);
    expect(playback.getState().mode).toBe("walkthrough");
    expect(playback.getState().playing).toBe(false);
    expect(narrate).toHaveBeenCalledTimes(spoken);
    playback.dispose();
  });
  it("leaves StrictMode cleanup paused instead of reporting a cancelled timer as playing", () => {
    vi.useFakeTimers();
    const playback = new TourPlayback({ navigate: vi.fn(), narrate: vi.fn(), stopNarration: vi.fn() });
    const context = { roundId: "accepted", latestRoundId: "accepted", plan: buildWalkthrough(candidate()), buildReveal: true, active: true };
    playback.sync(context); playback.dispose(); playback.sync(context);
    expect(playback.getState().playing).toBe(false);
    expect(vi.getTimerCount()).toBe(0);
    playback.play(); vi.advanceTimersByTime(3100);
    expect(playback.getState().mode).toBe("ready");
    playback.dispose(); vi.useRealTimers();
  });
  it("does not narrate or retain a playback timer when manual editing declines guided navigation", () => {
    vi.useFakeTimers();
    const narrate = vi.fn();
    let playback: TourPlayback;
    playback = new TourPlayback({ navigate: () => { playback.pause(); return false; }, narrate, stopNarration: vi.fn() });
    playback.sync({ roundId: "current", latestRoundId: "current", plan: buildWalkthrough(candidate()), buildReveal: false, active: true });
    playback.play();
    expect(narrate).not.toHaveBeenCalled();
    expect(playback.getState().playing).toBe(false);
    expect(vi.getTimerCount()).toBe(0);
    playback.dispose(); vi.useRealTimers();
  });
  it("pauses on hide, requires explicit resume, and drops stale callbacks on historical selection and scope reset", () => {
    vi.useFakeTimers();
    const plan = buildWalkthrough(candidate());
    const navigate = vi.fn(); const narrate = vi.fn(); const stopNarration = vi.fn();
    const playback = new TourPlayback({ navigate, narrate, stopNarration });
    const current = { roundId: "new", latestRoundId: "new", plan, buildReveal: true, active: true };
    playback.sync(current);
    playback.sync({ ...current, active: false });
    expect(playback.getState().playing).toBe(false);
    vi.advanceTimersByTime(10000);
    expect(playback.getState().revealedGroups).toBe(0);
    playback.sync(current);
    expect(playback.getState().playing).toBe(false);
    playback.play(); vi.advanceTimersByTime(3500);
    expect(playback.getState().mode).toBe("ready");
    narrate.mockClear();
    playback.play();
    expect(playback.getState()).toMatchObject({ mode: "walkthrough", playing: true, step: 0 });
    expect(navigate).toHaveBeenLastCalledWith(plan.steps[0]);
    playback.next(); expect(playback.getState()).toMatchObject({ playing: false, step: 1 });
    playback.previous(); expect(playback.getState().step).toBe(0);
    playback.pause(); expect(vi.getTimerCount()).toBe(0);
    playback.replayCreation(); expect(playback.getState().mode).toBe("assembly");
    playback.skip(); expect(playback.getState()).toMatchObject({ mode: "ready", revealedGroups: plan.groups.length });
    playback.play();
    playback.sync({ ...current, roundId: "old" });
    const spoken = narrate.mock.calls.length;
    expect(playback.getState()).toMatchObject({ historical: true, mode: "ready", playing: false });
    vi.advanceTimersByTime(10000);
    playback.play(); playback.next();
    expect(narrate).toHaveBeenCalledTimes(spoken);
    playback.sync({ ...current, roundId: null, plan: null, latestRoundId: null });
    expect(playback.getState()).toMatchObject({ mode: "empty", roundId: null });
    expect(vi.getTimerCount()).toBe(0);
    playback.play(); playback.replayCreation();
    expect(narrate).toHaveBeenCalledTimes(spoken);
    expect(stopNarration).toHaveBeenCalled();
    playback.dispose(); vi.useRealTimers();
  });
});
